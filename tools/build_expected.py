#!/usr/bin/env python3
"""Convert the expected-strokes workbook into js/expected-data.js.

Usage: build_expected.py expected_strokes.xlsx js/expected-data.js   (needs openpyxl)

Sheet 1 holds one block per lie (TEE / FAIRWAY / ROUGH / SAND / RECOVERY SHOTS),
each with a distance column in yards and one column per handicap level.
Sheet 2 holds expected putts by distance in feet.
"""
import json, sys
import openpyxl

SECTIONS = {"TEE SHOTS": "tee", "FAIRWAY SHOTS": "fairway", "ROUGH SHOTS": "rough",
            "SAND SHOTS": "bunker", "RECOVERY SHOTS": "recovery"}

def main(src, dst):
    wb = openpyxl.load_workbook(src, data_only=True)
    shots, putts = wb.worksheets[0], wb.worksheets[1]
    out, levels, cur = {}, None, None
    for row in shots.iter_rows(values_only=True):
        head = row[0]
        if isinstance(head, str) and head.strip() in SECTIONS:
            cur = out.setdefault(SECTIONS[head.strip()], {"d": [], "v": []})
        elif head == "Distance":
            levels = [str(x) for x in row[1:9]]
        elif isinstance(head, (int, float)) and cur is not None:
            cur["d"].append(head); cur["v"].append(list(row[1:9]))
    green = out.setdefault("green", {"d": [], "v": []})
    for row in putts.iter_rows(min_row=2, values_only=True):
        if isinstance(row[0], (int, float)):
            green["d"].append(row[0]); green["v"].append(list(row[1:9]))
    with open(dst, "w") as f:
        f.write("// Generated by tools/build_expected.py. Expected strokes to hole out by lie,\n"
                "// distance (yards; feet on the green) and handicap level.\n")
        f.write("export const LEVELS = " + json.dumps(levels) + ";\n")
        f.write("export const TABLES = " + json.dumps(out, separators=(",", ":")) + ";\n")
    print(levels, {k: len(v["d"]) for k, v in out.items()})

if __name__ == "__main__":
    main(*sys.argv[1:3])
